-- Antes de usar: crie um usuário em Authentication > Users.
-- Depois, ao final deste script, insira o UUID desse usuário na tabela admin_users.

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.drinks (
  id bigint generated by default as identity primary key,
  name text not null,
  category text,
  description text,
  price numeric(10,2) not null default 0 check (price >= 0),
  image_url text,
  image_path text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.quotes (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  event text,
  event_date date,
  guests integer check (guests is null or guests > 0),
  message text,
  status text not null default 'Novo'
    check (status in ('Novo','Em atendimento','Concluído','Cancelado')),
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

alter table public.admin_users enable row level security;
alter table public.drinks enable row level security;
alter table public.quotes enable row level security;

drop policy if exists "admin users read own row" on public.admin_users;
create policy "admin users read own row"
on public.admin_users for select to authenticated
using (user_id = (select auth.uid()));

drop policy if exists "public reads active drinks" on public.drinks;
create policy "public reads active drinks"
on public.drinks for select to anon, authenticated
using (active = true or public.is_admin());

drop policy if exists "admins manage drinks" on public.drinks;
create policy "admins manage drinks"
on public.drinks for all to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "public submits quotes" on public.quotes;
create policy "public submits quotes"
on public.quotes for insert to anon, authenticated
with check (status = 'Novo');

drop policy if exists "admins read quotes" on public.quotes;
create policy "admins read quotes"
on public.quotes for select to authenticated
using (public.is_admin());

drop policy if exists "admins update quotes" on public.quotes;
create policy "admins update quotes"
on public.quotes for update to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "admins delete quotes" on public.quotes;
create policy "admins delete quotes"
on public.quotes for delete to authenticated
using (public.is_admin());

grant select on public.admin_users to authenticated;
grant select on public.drinks to anon, authenticated;
grant insert on public.quotes to anon, authenticated;
grant select, insert, update, delete on public.drinks to authenticated;
grant select, update, delete on public.quotes to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- Storage: bucket público para leitura de imagens.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('drinks-images', 'drinks-images', true, 4194304,
        array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set
  public = true,
  file_size_limit = 4194304,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "public reads drink images" on storage.objects;
create policy "public reads drink images"
on storage.objects for select to anon, authenticated
using (bucket_id = 'drinks-images');

drop policy if exists "admins upload drink images" on storage.objects;
create policy "admins upload drink images"
on storage.objects for insert to authenticated
with check (bucket_id = 'drinks-images' and public.is_admin());

drop policy if exists "admins update drink images" on storage.objects;
create policy "admins update drink images"
on storage.objects for update to authenticated
using (bucket_id = 'drinks-images' and public.is_admin())
with check (bucket_id = 'drinks-images' and public.is_admin());

drop policy if exists "admins delete drink images" on storage.objects;
create policy "admins delete drink images"
on storage.objects for delete to authenticated
using (bucket_id = 'drinks-images' and public.is_admin());

